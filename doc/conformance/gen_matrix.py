_SYMBOLS = {}


def _symbols(path):
    """qualified name -> line of the classes, functions and module-level
    names of wcf/<path> (records/ for the record modules), as they are
    now."""
    if path not in _SYMBOLS:
        import ast
        full = os.path.join(REPO, 'wcf', path if path in (
            'datatypes.py', 'dictionary.py', 'errors.py', 'session.py',
            'xml2records.py', 'xmltext.py') else os.path.join('records', path))
        table = {}

        def walk(node, prefix):
            for child in ast.iter_child_nodes(node):
                if isinstance(child, (ast.FunctionDef, ast.ClassDef)):
                    table.setdefault(prefix + child.name, child.lineno)
                    walk(child, prefix + child.name + '.')
                elif isinstance(child, (ast.Assign, ast.AnnAssign)):
                    targets = child.targets if isinstance(child, ast.Assign) else [child.target]
                    for target in targets:
                        if isinstance(target, ast.Name):
                            table.setdefault(prefix + target.id, child.lineno)
        walk(ast.parse(open(full).read()), '')
        _SYMBOLS[path] = table
    return _SYMBOLS[path]


def translate(text):
    """Write the current line of every symbol: "file.py `Q.name`" becomes
    "file.py:LINE `Q.name`", and a following "`other`" of the same file
    ":LINE `other`". An unknown symbol of a file stops the build, so that
    the matrix never points to a line that moved."""
    out, current, pos = [], None, 0
    for m in re.finditer(r'(\w+\.py) `([\w.]+)`|`([\w.]+)`', text):
        out.append(text[pos:m.start()])
        pos = m.end()
        if m.group(1):
            current, symbol = m.group(1), m.group(2)
            if symbol not in _symbols(current):
                raise SystemExit('%s `%s` not found' % (current, symbol))
            out.append('%s:%d `%s`' % (current, _symbols(current)[symbol], symbol))
        elif current is not None and m.group(3) in _symbols(current):
            out.append(':%d `%s`' % (_symbols(current)[m.group(3)], m.group(3)))
        else:
            out.append(m.group(0))  # not a symbol of the file (a message...)
    out.append(text[pos:])
    return ''.join(out)


