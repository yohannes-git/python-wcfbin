def short(test_id):
    """tests.test_x.Class.test_y -> test_x::test_y; doctest ids as is."""
    if test_id.startswith('tests.'):
        parts = test_id.split('.')
        return '%s::%s' % (parts[1], parts[-1])
    return 'doctest:' + test_id


def rt_tests(t, kind):
    found = evidence[kind].get(str(t), [])
    return [short(x) for x in found]


def where(cls):
    source = cls
    if 'char' in vars(cls):     # generated by letter_records()
        source = cls.__mro__[1]
    path = inspect.getsourcefile(source).replace(REPO + '/wcf/', '')
    path = path.replace('records/', '')
    line = inspect.getsourcelines(source)[1]
    if source is cls:
        return '%s:%d `%s`' % (path, line, cls.__name__)
    return '`%s` (%s:%d `%s`)' % (cls.__name__, path, line, source.__name__)


