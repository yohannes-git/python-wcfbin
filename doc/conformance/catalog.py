def _element(sec, cls_ref, prefix, name_kind, ex, ex_tests, tests):
    """Requirements of an element record section."""
    rows = []
    if prefix == 'str':
        rows += [
            ('NBFX-%s-PREFIX-NONZERO' % sec, 'Prefix: "The length of this String MUST be nonzero"',
             cls_ref + '; ' + NAMES, tests.get('PN', []), 'C' if tests.get('PN') else 'I', ''),
            ('NBFX-%s-PREFIX-NOT-XMLNS' % sec, 'Prefix: "MUST NOT be "xmlns""',
             cls_ref + '; ' + NAMES, tests.get('PX', []), 'C' if tests.get('PX') else 'I', ''),
        ]
    ref = cls_ref + '; ' + (DNAMES if name_kind == 'dict' else NAMES)
    rows += [
        ('NBFX-%s-NAME-NONZERO' % sec, 'Name: "The length of this String MUST be nonzero"', ref,
         tests.get('NN', []), 'C' if tests.get('NN') else 'I',
         'For a DictionaryString, the referenced string (static 0xA2 is "").' if name_kind == 'dict' else ''),
        ('NBFX-%s-NAME-NOT-XMLNS' % sec, 'Name: "The name MUST NOT be "xmlns""', ref,
         tests.get('NX', []), 'C' if tests.get('NX') else 'I', ''),
    ]
    if prefix == 'letter':
        rows.append(('NBFX-%s-PREFIX-FROM-TYPE' % sec, '"The prefix ... is determined by the record type"',
                     cls_ref + '; base.py `letter_records`', tests.get('PT', []),
                     'C' if tests.get('PT') else 'I', 'Each letter: NBFX-2.1.1-RT-* rows.'))
    if ex:
        rows.append(('NBFX-%s-EX' % sec, ex, cls_ref + '; base.py `start_tag`', ex_tests,
                     'C' if ex_tests else 'I', ''))
    return rows


